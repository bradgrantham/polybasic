#!/usr/bin/env python3
"""Turn apple2e's font image into machines/apple2/font.h.

usage: tools/mkfont.py apple2font.ppm > machines/apple2/font.h

The image is a binary PPM holding 96 glyphs (ASCII 32..127), each 7 wide and
8 tall, packed left to right, top to bottom.  Each output byte is one glyph
row; bit 0 is the leftmost dot.
"""
import sys


def main():
    data = open(sys.argv[1], "rb").read()
    fields = data.split(None, 4)
    assert fields[0] == b"P6"
    w, h = int(fields[1]), int(fields[2])
    px = fields[4]
    across = w // 7
    art = "--art" in sys.argv
    print("// Apple II character set, ASCII 32..127, 7x8 dots; bit 0 is the left dot.")
    print("// Generated by tools/mkfont.py from apple2font.ppm in bradgrantham/apple2e.")
    print("static const uint8_t font[96][8] = {")
    for g in range(96):
        gx, gy = (g % across) * 7, (g // across) * 8
        rows = []
        for j in range(8):
            v = 0
            for i in range(7):
                if px[((gy + j) * w + gx + i) * 3] > 127:
                    v |= 1 << i
            rows.append(v)
            if art:
                sys.stderr.write("".join("#" if v >> i & 1 else "." for i in range(7)) + "\n")
        if art:
            sys.stderr.write("\n")
        print("    {%s}," % ", ".join("0x%02X" % v for v in rows))
    print("};")


main()
